import type { Metadata } from "next";
import { Geist, Geist_Mono, JetBrains_Mono } from "next/font/google";
import { Suspense } from "react";
import "./globals.css";
import { logout } from "./actions/auth";
import { cookies } from "next/headers";
import { cn } from "@/lib/utils";
import Link from "next/link";
import { OnlineWidget } from "@/components/OnlineWidget";

const jetbrainsMono = JetBrains_Mono({subsets:['latin'],variable:'--font-mono'});

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

async function LogoutControl() {
  const isSignedUp = Boolean((await cookies()).get("session")?.value);

  if (!isSignedUp) return null;

  return (
    <div className="flex items-center gap-4">
      <Link className="font-semibold transition-colors hover:text-brand-secondary" href="/me">Mon profil</Link>
      <form action={logout}>
        <button
          className="rounded-full bg-brand-secondary px-3 py-2 text-sm font-semibold text-brand-main transition-colors hover:bg-brand-tertiary"
          type="submit"
        >
          logout
        </button>
      </form>
    </div>
  );
}

export default async function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={cn("h-full", "antialiased", geistSans.variable, geistMono.variable, "font-mono", jetbrainsMono.variable)}
    >
      <body className="min-h-full flex flex-col">
        <header className="border-b-4 border-brand-tertiary bg-brand-main text-white">
          <nav className="mx-auto flex w-full max-w-5xl items-center justify-between gap-4 px-4 py-3">
            <OnlineWidget />
            <ul className="flex items-center gap-5">
              <li><Link className="font-semibold transition-colors hover:text-brand-secondary" href="/">Accueil</Link></li>
              <li><Link className="font-semibold transition-colors hover:text-brand-secondary" href="/drops">Drops</Link></li>
            </ul>
            <Suspense fallback={null}>
              <LogoutControl />
            </Suspense>
          </nav>
        </header>
        <Suspense fallback={<main className="page-container"><p className="text-muted">Chargement…</p></main>}>
          {children}
        </Suspense>
      </body>
    </html>
  );
}
